/* =============================================================================
   Dr. Dhruti Kunjit Patel — site behaviour
   Data comes from data/substack.js (generated by tools/fetch_substack.py).
   ========================================================================== */

(function () {
  'use strict';

  var DATA = window.SUBSTACK_DATA || { articles: [], notes: [], updated: null };
  var $  = function (sel, ctx) { return (ctx || document).querySelector(sel); };
  var $$ = function (sel, ctx) { return Array.prototype.slice.call((ctx || document).querySelectorAll(sel)); };

  /* ---------------------------------------------------------------- theme */

  var root = document.documentElement;
  var themeBtn = $('#themeToggle');

  function applyTheme(mode) {
    root.setAttribute('data-theme', mode);
    if (themeBtn) {
      themeBtn.setAttribute(
        'aria-label',
        mode === 'dark' ? 'Switch to light theme' : 'Switch to dark theme'
      );
    }
  }

  var stored = null;
  try { stored = localStorage.getItem('dkp-theme'); } catch (e) { /* private mode */ }

  if (stored === 'dark' || stored === 'light') {
    applyTheme(stored);
  } else {
    applyTheme(window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light');
  }

  if (themeBtn) {
    themeBtn.addEventListener('click', function () {
      var next = root.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
      applyTheme(next);
      try { localStorage.setItem('dkp-theme', next); } catch (e) { /* ignore */ }
    });
  }

  /* ------------------------------------------------------------ nav / ui */

  var header = $('#siteHeader');
  var nav = $('#siteNav');
  var menuBtn = $('#menuToggle');
  var progress = $('#scrollProgress');

  if (menuBtn && nav) {
    menuBtn.addEventListener('click', function () {
      var open = nav.classList.toggle('is-open');
      menuBtn.setAttribute('aria-expanded', String(open));
      menuBtn.setAttribute('aria-label', open ? 'Close menu' : 'Open menu');
    });
    nav.addEventListener('click', function (e) {
      if (e.target.tagName === 'A') {
        nav.classList.remove('is-open');
        menuBtn.setAttribute('aria-expanded', 'false');
      }
    });
  }

  var sections = $$('main section[id]');
  var navLinks = $$('.site-nav a');

  function onScroll() {
    var y = window.scrollY || window.pageYOffset;

    if (header) header.classList.toggle('is-stuck', y > 8);

    if (progress) {
      var max = document.documentElement.scrollHeight - window.innerHeight;
      progress.style.width = (max > 0 ? (y / max) * 100 : 0) + '%';
    }

    var current = '';
    for (var i = 0; i < sections.length; i++) {
      if (sections[i].offsetTop - 140 <= y) current = sections[i].id;
    }
    navLinks.forEach(function (a) {
      a.classList.toggle('is-active', a.getAttribute('href') === '#' + current);
    });
  }

  var ticking = false;
  window.addEventListener('scroll', function () {
    if (ticking) return;
    ticking = true;
    window.requestAnimationFrame(function () { onScroll(); ticking = false; });
  }, { passive: true });
  onScroll();

  var yearEl = $('#year');
  if (yearEl) yearEl.textContent = String(new Date().getFullYear());

  /* --------------------------------------------------------- formatting */

  function fmtDate(iso) {
    if (!iso) return '';
    var d = new Date(iso);
    if (isNaN(d)) return '';
    return d.toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
  }

  function relative(iso) {
    var d = new Date(iso);
    if (isNaN(d)) return '';
    var days = Math.floor((Date.now() - d.getTime()) / 86400000);
    if (days <= 0) return 'Today';
    if (days === 1) return 'Yesterday';
    if (days < 7) return days + ' days ago';
    return fmtDate(iso);
  }

  function esc(str) {
    return String(str == null ? '' : str)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }

  var HEART = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M12 20.3 4.6 13a4.6 4.6 0 0 1 6.5-6.5l.9.9.9-.9A4.6 4.6 0 0 1 19.4 13Z"/></svg>';
  var ARROW = '<svg viewBox="0 0 24 24" width="13" height="13" aria-hidden="true"><path d="M5 12h13M13 6l6 6-6 6" stroke-linecap="round" stroke-linejoin="round"/></svg>';

  /* ---------------------------------------------------------- articles */

  // Articles written on this site (posts/*.md, built by tools/build_posts.py)
  // sit in the same list as the Substack ones, newest first. Each keeps an
  // `own` flag so the card can say where it lives.
  var OWN = (window.SITE_POSTS && window.SITE_POSTS.items) || [];

  var articles = OWN.concat(DATA.articles || []).sort(function (a, b) {
    return String(b.date || '').localeCompare(String(a.date || ''));
  });
  var grid = $('#articleGrid');
  var emptyMsg = $('#articleEmpty');
  var filterBox = $('#articleFilters');
  var searchInput = $('#articleSearch');

  // Filter by what a piece IS, not by Substack tags. The tag lists overlap so
  // heavily (almost every post carries IPO + Equity Research + Stock Analysis)
  // that tag filters all returned the same articles. Categories are assigned
  // in tools/fetch_substack.py.
  var CATEGORIES = [
    { key: 'company', label: 'IPO & RHP analysis' },
    { key: 'method',  label: 'Frameworks' },
    { key: 'markets', label: 'Markets & sectors' }
  ];

  var activeTopic = 'all';
  var query = '';

  function articleMatches(a) {
    if (activeTopic !== 'all' && a.category !== activeTopic) return false;
    if (query) {
      var hay = [a.title, a.subtitle, a.excerpt, (a.tags || []).join(' ')].join(' ').toLowerCase();
      if (hay.indexOf(query) === -1) return false;
    }
    return true;
  }

  function articleCard(a, isFeature) {
    var tags = (a.tags || []).slice(0, 3).map(function (t) {
      return '<span class="post-tag">' + esc(t) + '</span>';
    }).join('');

    var badge = a.own
      ? '<span class="post-badge is-own">On this site</span>'
      : (isFeature ? '<span class="post-badge">Latest</span>' : '');

    var thumb = a.image
      ? '<div class="post-thumb">' + badge +
          '<img src="' + esc(a.image) + '" alt="" loading="lazy" decoding="async">' +
        '</div>'
      : '';

    // Own articles open in this tab; Substack ones leave the site.
    var target = a.own ? '' : ' target="_blank" rel="noopener"';

    return '' +
      '<a class="post-card' + (isFeature ? ' is-feature' : '') + '" href="' + esc(a.url) + '"' + target + '>' +
        thumb +
        '<div class="post-body">' +
          '<p class="post-meta">' +
            // Without a cover there is no image to sit the badge on, so the
            // "hosted here" marker goes in the meta line instead.
            (a.own && !a.image ? '<span class="own-flag">On this site</span>' : '') +
            '<time datetime="' + esc(a.date) + '">' + fmtDate(a.date) + '</time>' +
            '<span class="dot">·</span><span>' + a.readingMinutes + ' min read</span>' +
            (a.wordcount ? '<span class="dot">·</span><span>' + a.wordcount.toLocaleString() + ' words</span>' : '') +
          '</p>' +
          '<h3>' + esc(a.title) + '</h3>' +
          (a.subtitle ? '<p class="post-sub">' + esc(a.subtitle) + '</p>' : '') +
          '<div class="post-tags">' + tags + '</div>' +
          '<div class="post-foot">' +
            '<span class="post-read">' + (a.own ? 'Read article' : 'Read on Substack') + ARROW + '</span>' +
            (a.likes ? '<span class="likes">' + HEART + a.likes + '</span>' : '') +
          '</div>' +
        '</div>' +
      '</a>';
  }

  function renderArticles() {
    if (!grid) return;
    var list = articles.filter(articleMatches);
    grid.innerHTML = list.map(function (a, i) {
      // Feature the newest article only in the unfiltered default view.
      return articleCard(a, i === 0 && activeTopic === 'all' && !query);
    }).join('');
    if (emptyMsg) emptyMsg.hidden = list.length > 0;
  }

  function buildFilters() {
    if (!filterBox) return;

    function countIn(key) {
      return articles.filter(function (a) { return a.category === key; }).length;
    }

    var html = '<button class="chip is-active" type="button" data-topic="all">' +
      'All <span class="chip-count">' + articles.length + '</span></button>';

    html += CATEGORIES.map(function (c) {
      var n = countIn(c.key);
      if (!n) return '';  // hide a bucket until something lands in it
      return '<button class="chip" type="button" data-topic="' + esc(c.key) + '">' +
        esc(c.label) + ' <span class="chip-count">' + n + '</span></button>';
    }).join('');

    filterBox.innerHTML = html;

    filterBox.addEventListener('click', function (e) {
      var btn = e.target.closest('.chip');
      if (!btn) return;
      activeTopic = btn.getAttribute('data-topic');
      $$('.chip', filterBox).forEach(function (c) { c.classList.toggle('is-active', c === btn); });
      renderArticles();
    });
  }

  if (searchInput) {
    var t;
    searchInput.addEventListener('input', function () {
      clearTimeout(t);
      t = setTimeout(function () {
        query = searchInput.value.trim().toLowerCase();
        renderArticles();
      }, 140);
    });
  }

  buildFilters();
  renderArticles();

  var stamp = $('#articleStamp');
  if (stamp && DATA.updated) {
    stamp.textContent = 'Showing ' + articles.length + ' article' + (articles.length === 1 ? '' : 's') +
      ' · last synced from Substack on ' + fmtDate(DATA.updated);
  }

  var statEl = $('[data-stat="articles"]');
  if (statEl) statEl.textContent = articles.length ? articles.length : '—';

  // Newest article, surfaced in the hero band.
  var heroLatest = $('#heroLatest');
  if (heroLatest && articles.length) {
    var newest = articles[0];
    heroLatest.href = newest.url;
    heroLatest.target = '_blank';
    heroLatest.rel = 'noopener';
    heroLatest.innerHTML =
      (newest.image
        ? '<img src="' + esc(newest.image) + '" alt="" loading="lazy" decoding="async">'
        : '') +
      '<div>' +
        '<p class="hl-kicker"><span class="pulse"></span>Latest analysis</p>' +
        '<h2>' + esc(newest.title) + '</h2>' +
        '<p class="hl-meta">' + fmtDate(newest.date) + ' · ' + newest.readingMinutes + ' min read</p>' +
      '</div>';
    heroLatest.hidden = false;
  }

  /* ------------------------------------------------------------- notes */

  var notes = (DATA.notes || []).slice();
  var feed = $('#noteFeed');
  var moreBtn = $('#noteMore');
  var AVATAR = 'assets/img/dhruti-patel.jpg';
  var PAGE = 6;
  var shown = PAGE;

  function noteCard(n) {
    var body = esc(n.body).trim();
    var longNote = body.length > 420;

    var img = n.image
      ? '<img class="note-img" src="' + esc(n.image) + '" alt="" loading="lazy" decoding="async">'
      : '';

    var linked = n.linkedPost && n.linkedPost.url
      ? '<a class="note-post" href="' + esc(n.linkedPost.url) + '" target="_blank" rel="noopener">' +
          '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M4 5h16v3H4zM4 10h16v3H4zM4 15l8 4 8-4v5l-8 4-8-4z"/></svg>' +
          esc(n.linkedPost.title) +
        '</a>'
      : '';

    return '' +
      '<article class="note">' +
        '<div class="note-head">' +
          '<img class="note-avatar" src="' + AVATAR + '" alt="" loading="lazy">' +
          '<span class="note-who">' +
            '<b>Dr. Dhruti Patel</b>' +
            '<time datetime="' + esc(n.date) + '">' + relative(n.date) + '</time>' +
          '</span>' +
        '</div>' +
        (body ? '<p class="note-text' + (longNote ? ' is-clamped' : '') + '">' + body + '</p>' : '') +
        (longNote ? '<button class="note-toggle" type="button">Read more</button>' : '') +
        img +
        linked +
        '<div class="note-foot">' +
          (n.likes ? '<span class="likes">' + HEART + n.likes + '</span>' : '') +
          (n.restacks ? '<span>' + n.restacks + ' restack' + (n.restacks === 1 ? '' : 's') + '</span>' : '') +
          '<a href="' + esc(n.url) + '" target="_blank" rel="noopener">View note</a>' +
        '</div>' +
      '</article>';
  }

  function renderNotes() {
    if (!feed) return;
    feed.innerHTML = notes.slice(0, shown).map(noteCard).join('');
    if (moreBtn) {
      if (shown >= notes.length) {
        moreBtn.style.display = notes.length > PAGE ? '' : 'none';
        moreBtn.textContent = 'Show fewer notes';
        moreBtn.dataset.mode = 'less';
      } else {
        moreBtn.style.display = '';
        moreBtn.textContent = 'Show more notes (' + (notes.length - shown) + ')';
        moreBtn.dataset.mode = 'more';
      }
    }
  }

  if (feed) {
    feed.addEventListener('click', function (e) {
      var btn = e.target.closest('.note-toggle');
      if (!btn) return;
      var text = btn.previousElementSibling;
      var clamped = text.classList.toggle('is-clamped');
      btn.textContent = clamped ? 'Read more' : 'Show less';
    });
  }

  if (moreBtn) {
    moreBtn.addEventListener('click', function () {
      if (moreBtn.dataset.mode === 'less') {
        shown = PAGE;
        renderNotes();
        var anchor = $('#notes');
        if (anchor) anchor.scrollIntoView({ behavior: 'smooth', block: 'start' });
      } else {
        shown = Math.min(shown + PAGE, notes.length);
        renderNotes();
      }
      observeReveals();
    });
  }

  renderNotes();

  /* ------------------------------------------------------------ reveal */

  var io = null;
  if ('IntersectionObserver' in window) {
    io = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible');
          io.unobserve(entry.target);
        }
      });
    }, { rootMargin: '0px 0px -8% 0px', threshold: 0.05 });
  }

  function observeReveals() {
    if (!io) return;
    $$('.post-card, .note, .ach-card, .tl-item, .owners-grid li, .contact-card, .col-block')
      .forEach(function (el) {
        if (el.classList.contains('reveal')) return;
        el.classList.add('reveal');
        io.observe(el);
      });
  }
  observeReveals();

  /* --------------------------------------------------- no-data fallback */

  if (!articles.length && grid) {
    grid.innerHTML =
      '<p class="empty-state">Articles could not be loaded. Read everything at ' +
      '<a class="text-link" href="https://mpulseindia.substack.com/" target="_blank" rel="noopener">mpulseindia.substack.com</a>.</p>';
  }
  if (!notes.length && feed) {
    feed.innerHTML =
      '<p class="empty-state">Notes could not be loaded. Follow along at ' +
      '<a class="text-link" href="https://substack.com/@mpulseindia" target="_blank" rel="noopener">substack.com/@mpulseindia</a>.</p>';
    if (moreBtn) moreBtn.style.display = 'none';
  }
})();
